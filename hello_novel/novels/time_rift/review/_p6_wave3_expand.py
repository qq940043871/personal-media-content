def count_cjk(text):
    return len(re.findall(r'[\u4e00-\u9fff]', text))

def body_dash(text):
    lines = text.splitlines()
    body_lines = []
    in_footer = False
    for i, line in enumerate(lines):
        if i == 0 and line.strip().startswith('#'):
            continue
        if '本章关键点' in line:
            in_footer = True
        if in_footer:
            continue
        body_lines.append(line)
    return '\n'.join(body_lines).count('——')

def apply_one(n, spec, compress_dash=False):
    p = CH / f'chapter-{n:03d}.md'
    raw = p.read_text(encoding='utf-8')
    if raw.startswith('\ufeff'):
        raw = raw[1:]
    before = count_cjk(raw)
    needle = spec['insert_before']
    exp = spec['text']
    if needle in raw:
        raw2 = raw.replace(needle, exp.strip() + '\n\n' + needle, 1)
        how = 'ok'
    else:
        # try common tails
        for alt in ['公告栏玻璃反着光', '小巷深处的木牌', '楼梯转角的配电箱', '林晓实验室', '她走在走廊里']:
            if alt in raw:
                raw2 = raw.replace(alt, exp.strip() + '\n\n' + alt, 1)
                how = f'alt:{alt[:8]}'
                break
        else:
            raw2 = raw.replace('\n---\n**本章关键点', exp + '\n---\n**本章关键点', 1)
            how = 'fallback'
    # dash compress for high-dash chapters: replace explanatory —— with 、，：
    if compress_dash:
        # count body dash
        if body_dash(raw2) > 8:
            # conservative replacements on body only
            parts = raw2.split('\n---\n**本章关键点')
            body = parts[0]
            footer = ('\n---\n**本章关键点' + parts[1]) if len(parts) > 1 else ''
            # replace some common patterns
            replacements = [
                ('不是……而是', None),  # skip
            ]
            # pattern: X——Y as explanation → X，Y
            # do targeted: 选择——选择 → 选择，选择
            body2 = body
            # generic: 如果 —— 后面是解释，用逗号
            body2 = re.sub(r'——选择', '，选择', body2)
            body2 = re.sub(r'——它是', '：它是', body2)
            body2 = re.sub(r'——不是', '，不是', body2)
            body2 = re.sub(r'——而是', '，而是', body2)
            body2 = re.sub(r'——一种', '，一种', body2)
            body2 = re.sub(r'——在', '，在', body2)
            body2 = re.sub(r'——所有', '，所有', body2)
            body2 = re.sub(r'——一', '，一', body2)
            body2 = re.sub(r'——有人', '，有人', body2)
            body2 = re.sub(r'——因为', '，因为', body2)
            body2 = re.sub(r'——每', '，每', body2)
            body2 = re.sub(r'——那', '，那', body2)
            body2 = re.sub(r'——这', '，这', body2)
            body2 = re.sub(r'——但', '，但', body2)
            body2 = re.sub(r'——她', '，她', body2)
            body2 = re.sub(r'——他', '，他', body2)
            body2 = re.sub(r'——它', '，它', body2)
            body2 = re.sub(r'——ARIA', '，ARIA', body2)
            body2 = re.sub(r'——李明', '，李明', body2)
            body2 = re.sub(r'——从', '，从', body2)
            body2 = re.sub(r'——到', '，到', body2)
            body2 = re.sub(r'——像', '，像', body2)
            body2 = re.sub(r'——一种', '，一种', body2)
            body2 = re.sub(r'——有的', '，有的', body2)
            body2 = re.sub(r'——它们', '，它们', body2)
            body2 = re.sub(r'——我们', '，我们', body2)
            body2 = re.sub(r'——存在', '，存在', body2)
            body2 = re.sub(r'——记忆', '，记忆', body2)
            body2 = re.sub(r'——永恒', '，永恒', body2)
            body2 = re.sub(r'——真实', '，真实', body2)
            body2 = re.sub(r'——有限', '，有限', body2)
            body2 = re.sub(r'——连接', '，连接', body2)
            body2 = re.sub(r'——爱', '，爱', body2)
            raw2 = body2 + footer
    p.write_text(raw2, encoding='utf-8')
    after = count_cjk(raw2)
    dash = body_dash(raw2)
    print(f'ch{n}: {before}→{after} {"OK" if after>=5000 else "SHORT"} dash={dash} ({how})')
    return after, dash

