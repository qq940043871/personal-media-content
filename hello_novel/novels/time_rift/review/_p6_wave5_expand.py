def apply_one(n, spec, do_dash=False):
    p = CH / f'chapter-{n:03d}.md'
    raw = p.read_text(encoding='utf-8')
    if raw.startswith('\ufeff'):
        raw = raw[1:]
    before = count_cjk(raw)
    bdash_b = body_dash(raw)
    exp = spec['text']
    needle = spec.get('insert_before')
    raw2, how = insert_exp(raw, exp, needle)
    if do_dash:
        raw2 = compress_dash_in(raw2)
    p.write_text(raw2, encoding='utf-8')
    after = count_cjk(raw2)
    bdash_a = body_dash(raw2)
    print(f'ch{n}: {before}→{after} {"OK" if after>=5000 else "SHORT"} dash {bdash_b}→{bdash_a} ({how})')

