def count_cjk(text):
    return len(re.findall(r'[\u4e00-\u9fff]', text))

def body_dash(text):
    lines = text.splitlines()
    body_lines = []
    in_footer = False
    for i, line in enumerate(lines):
        if i == 0 and line.strip().startswith('#'):
            continue
        if '本章关键点' in line:
            in_footer = True
        if in_footer:
            continue
        body_lines.append(line)
    return '\n'.join(body_lines).count('——')

def insert_exp(raw, exp, needle=None):
    if needle and needle in raw:
        return raw.replace(needle, exp.strip() + '\n\n' + needle, 1), 'ok'
    for alt in ['公告栏玻璃反着光', '小巷深处的木牌', '楼梯转角的配电箱', '林晓实验室',
                '墙上的观察窗标记旁', '她走在走廊里', '她在学习用自己的声音说话',
                '楼梯转角的配电箱门虚掩着']:
        if alt in raw:
            return raw.replace(alt, exp.strip() + '\n\n' + alt, 1), 'alt'
    if '\n---\n**本章关键点' in raw:
        return raw.replace('\n---\n**本章关键点', '\n' + exp + '\n---\n**本章关键点', 1), 'footer'
    return raw.rstrip() + '\n' + exp, 'append'

