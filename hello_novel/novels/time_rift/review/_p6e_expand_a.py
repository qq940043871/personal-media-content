def apply_one(n: int, text: str) -> None:
    p = CH / f"chapter-{n:03d}.md"
    raw = p.read_text(encoding="utf-8")
    if raw.startswith("\ufeff"):
        raw = raw[1:]
    before = body_cjk_count(raw)
    # idempotency: skip if expansion marker already present
    marker = text.strip()[:36]
    if marker and marker in raw:
        print(f"ch{n}: SKIP already expanded cjk={before}")
        return
    block = text.strip() + "\n\n"
    how = "footer"
    raw2 = None
    for alt in TAIL_MARKERS:
        if alt in raw:
            raw2 = raw.replace(alt, block + alt, 1)
            how = "alt:" + alt[:8]
            break
    if raw2 is None:
        for sep in ("\n---\n**本章关键点", "\n---\r\n**本章关键点"):
            if sep in raw:
                raw2 = raw.replace(sep, "\n" + block + sep.lstrip("\n"), 1)
                how = "footer-sep"
                break
    if raw2 is None:
        # find footer via --- + marker more loosely
        m = re.search(r"\n---\s*\n\*\*本章关键点", raw)
        if m:
            raw2 = raw[: m.start()] + "\n\n" + block + raw[m.start() :].lstrip("\n")
            how = "footer-re"
        else:
            raw2 = raw.rstrip() + "\n\n" + block
            how = "append"
    p.write_text(raw2, encoding="utf-8")
    after = body_cjk_count(raw2)
    d = body_dash(raw2)
    flag = "OK" if after >= 5000 else "SHORT"
    print(f"ch{n}: {before}→{after} {flag} dash={d} ({how})")


