    print("=== FINAL SCAN 61-120 ===")
    shorts = []
    highs = []
    for n in range(61, 121):
        p = ROOT / f"chapter-{n:03d}.md"
        if not p.exists():
            continue
        _, _, _, cjk, dash = split_chapter(p.read_text(encoding="utf-8-sig"))
        if cjk < 5000:
            shorts.append((n, cjk, dash))
        if dash > 8:
            highs.append((n, cjk, dash))
    print("CJK<5000:", len(shorts))
    for row in shorts:
        print(f"  {row[0]:03d} cjk={row[1]} dash={row[2]}")
    print("dash>8:", len(highs))
    for row in highs:
        print(f"  {row[0]:03d} cjk={row[1]} dash={row[2]}")


