FOOTER_RE = re.compile(r"\n---\s*\n\*\*本章关键点[：:]\*\*", re.M)
TITLE_RE = re.compile(r"^#[^\n]*\n")
CJK_RE = re.compile(r"[\u4e00-\u9fff]")


def split_chapter(text: str):
    m = FOOTER_RE.search(text)
    if m:
        head_body, footer = text[: m.start()], text[m.start() :]
    else:
        head_body, footer = text, "\n---\n**本章关键点：**\n"
    title_m = TITLE_RE.match(head_body)
    title = title_m.group(0) if title_m else ""
    body = head_body[len(title) :]
    # strip leading author-note block from body for measurement only
    measure = re.sub(r"^(?:---\s*\n)?(?:>.*\n)+", "", body)
    measure = re.sub(r"^---\s*\n", "", measure)
    cjk = len(CJK_RE.findall(measure))
    dash = body.count("——")
    return title, body, footer, cjk, dash


def reduce_dashes(text: str, max_keep: int = 6) -> str:
    parts = text.split("——")
    if len(parts) - 1 <= max_keep:
        return text
    out = [parts[0]]
    for i, p in enumerate(parts[1:], 1):
        prev = out[-1]
        if i <= max_keep:
            conn = "——"
        else:
            tail = prev[-4:] if prev else ""
            if re.search(r"(是|在|把|被|让|给|用|向|从|对|为|像)$", tail):
                conn = "，"
            elif re.match(r"\s*(是|不是|像|而是|像)", p):
                conn = "，"
            elif re.match(r"\s*[0-9一二三四五六七八九十]", p):
                conn = "："
            else:
                conn = "。"
        out.append(conn + p)
    return "".join(out)


