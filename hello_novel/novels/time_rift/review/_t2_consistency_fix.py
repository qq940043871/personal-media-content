def apply_batch(label, fixes):
    applied, failed = [], []
    for fname, pairs in fixes.items():
        p = root / fname
        if not p.exists():
            failed.append(f"{fname}: FILE MISSING")
            continue
        text = p.read_text(encoding="utf-8")
        for old, new in pairs:
            if old not in text:
                failed.append(f"{fname}: NOT FOUND: {old[:70]}...")
            else:
                text = text.replace(old, new)
                applied.append(fname)
        p.write_text(text, encoding="utf-8")
    print(f"{label} APPLIED {len(applied)}")
    for x in applied:
        print(" ", x)
    print(f"{label} FAILED {len(failed)}")
    for x in failed:
        print(" ", x)
    return applied, failed


