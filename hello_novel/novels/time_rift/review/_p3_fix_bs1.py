def clean_punct(t: str) -> str:
    t = re.sub(r"，，+", "，", t)
    t = re.sub(r"。。+", "。", t)
    t = re.sub(r"，。", "。", t)
    t = re.sub(r"。，", "。", t)
    t = re.sub(r"、、", "、", t)
    return t


def fix_ch184_dialogue(text: str) -> str:
    """ch184: incomplete dialogue trail-offs become ellipsis + close quote."""
    lines = text.split("\n")
    out = []
    for i, ln in enumerate(lines):
        if TOKEN not in ln:
            out.append(ln)
            continue
        # Dialogue line that ends with ，\1 (no closing quote) → ……"
        # e.g. `"ARIA。"他说，"你有没有感觉到，\1`
        if re.search(r"[，,]" + re.escape(TOKEN) + r"\s*$", ln) and ln.count('"') % 2 == 1:
            ln = re.sub(re.escape(TOKEN) + r"\s*$", "……\"", ln)
        # Dialogue line `"word，\1` mid-line, unclosed quote, next is blank/other speaker
        elif re.search(r"[，,]" + re.escape(TOKEN), ln) and '"' in ln:
            # If quote unclosed, close with ……"
            if ln.count('"') % 2 == 1:
                ln = ln.replace(TOKEN, "……\"")
            else:
                ln = ln.replace(TOKEN, "……")
        # `"word，\1。"` closed dialogue
        elif re.search(r"[，,]" + re.escape(TOKEN) + r"。", ln):
            ln = re.sub(re.escape(TOKEN) + r"。", "……。", ln)
        out.append(ln)
    return "\n".join(out)


def fix_narrative_bulk(text: str, chapter: str) -> str:
    """Generic narrative \1 repairs."""
    # Dialogue-ish: inside quotes, ，\1 at EOL or before " → ……
    def repl_dlg_eol(m):
        return m.group(1) + "……\""

    text = re.sub(
        r"([^\"\n]{1,80})，" + re.escape(TOKEN) + r"(?=\n\n)",
        lambda m: m.group(1) + "……\"",
        text,
    )
    # closed dialogue `"……，\1……"` → ellipsis
    text = re.sub(
        r"\"([^\"\n]{0,120})，" + re.escape(TOKEN) + r"([^\"\n]{0,40})\"",
        lambda m: '"' + m.group(1) + "……" + m.group(2) + '"',
        text,
    )
    # `"……，\1` unclosed at EOL
    text = re.sub(
        r"\"([^\"\n]{0,120})，" + re.escape(TOKEN) + r"\s*$",
        lambda m: '"' + m.group(1) + "……\"",
        text,
        flags=re.M,
    )

    # 不是A，\1。而是B。 → 不是A，而是B。
    text = re.sub(
        r"不是([^，。\n]{1,40})，" + re.escape(TOKEN) + r"。而是",
        r"不是\1，而是",
        text,
    )
    text = re.sub(
        r"不是([^，。\n]{1,40})，" + re.escape(TOKEN) + r"，而是",
        r"不是\1，而是",
        text,
    )
    # 因为A，\1。因为B → merge
    text = re.sub(
        r"，" + re.escape(TOKEN) + r"。而是",
        "，而是",
        text,
    )

    # 而是，\1。 / 而是\1X → careful
    text = re.sub(r"而是，" + re.escape(TOKEN) + r"。", "而是这样。", text)
    text = re.sub(r"而是，" + re.escape(TOKEN) + r"，", "而是这样，", text)
    text = re.sub(r"而是" + re.escape(TOKEN) + r"(?=[^\s，。！？；：\"'\n])", "而是", text)

    # 是\1 + CJK content (missing measure/classifier) → 是一种/是
    text = re.sub(r"是" + re.escape(TOKEN) + r"(?=[^\dA-Za-z])", "是", text)

    # 列表式：，\1； → ；
    text = re.sub(r"，" + re.escape(TOKEN) + r"；", "；", text)
    # 完整从句 + ，\1。 → 。
    text = re.sub(r"，" + re.escape(TOKEN) + r"。", "。", text)
    # 完整从句 + ，\1， → ，
    text = re.sub(r"，" + re.escape(TOKEN) + r"，", "，", text)
    # 完整从句 + ，\1" → 。"  or "
    text = re.sub(r"，" + re.escape(TOKEN) + r"(?=[\"'\n])", "", text)
    # remaining bare \1 (rare) — leave for leftover pass
    text = clean_punct(text)
    return text


def apply_exact(text: str, chapter: str) -> str:
    for old, new in EXACT.items():
        if old in text:
            n = text.count(old)
            text = text.replace(old, new)
            LOG[chapter].append(f"exact x{n}: {old[:40]}")
    return text


def apply_context(text: str, chapter: str) -> str:
    for old, new in CONTEXT:
        if old in text:
            n = text.count(old)
            text = text.replace(old, new)
            LOG[chapter].append(f"context x{n}: {old[:40]} → {new[:40]}")
    return text


def repair_chapter(path: Path) -> tuple[int, int]:
    t = path.read_text(encoding="utf-8")
    before = t.count(TOKEN)
    if before == 0:
        return 0, 0
    ch = path.name

    t = apply_exact(t, ch)
    if ch == "chapter-184.md":
        t = fix_ch184_dialogue(t)
    t = fix_narrative_bulk(t, ch)
    t = apply_context(t, ch)
    t = apply_exact(t, ch)  # re-apply after bulk
    t = clean_punct(t)

    after = t.count(TOKEN)
    if after < before:
        path.write_text(t, encoding="utf-8")
    return before, after


