def apply(n, path, block):
    text = path.read_text(encoding="utf-8-sig")
    cjk, _ = split_chapter(text)
    m = FOOTER_RE.search(text)
    if not m:
        return cjk, cjk
    fingerprint = None
    for line in block.splitlines():
        s = line.strip()
        if s.startswith("## ") and len(s) >= 4:
            fingerprint = s
            break
    if fingerprint and fingerprint in text:
        return cjk, cjk
    new_text = text[: m.start()] + block + text[m.start() :]
    path.write_text(new_text, encoding="utf-8")
    cjk2, _ = split_chapter(path.read_text(encoding="utf-8-sig"))
    return cjk, cjk2


def main():
    for n, block in BLOCKS.items():
        p = ROOT / f"chapter-{n:03d}.md"
        if not p.exists():
            print(n, "missing")
            continue
        a, b = apply(n, p, block)
        print(f"{n:03d} cjk {a}->{b}")

    print("=== FINAL SCAN 61-120 ===")
    under45 = []
    under50 = []
    highdash = []
    for n in range(61, 121):
        p = ROOT / f"chapter-{n:03d}.md"
        if not p.exists():
            continue
        t = p.read_text(encoding="utf-8-sig")
        cjk, dash = split_chapter(t)
        if cjk < 4500:
            under45.append((n, cjk))
        elif cjk < 5000:
            under50.append((n, cjk))
        if dash > 8:
            highdash.append((n, dash))
    print("under4500", under45)
    print("4500-4999", under50)
    print("dash>8", highdash)
    focus = [61,83,84,89,96,105,112,120]
    for n in focus:
        p = ROOT / f"chapter-{n:03d}.md"
        t = p.read_text(encoding="utf-8-sig")
        cjk, dash = split_chapter(t)
        print(f"FOCUS {n:03d} cjk={cjk} dash={dash}")


if __name__ == "__main__":
    main()
