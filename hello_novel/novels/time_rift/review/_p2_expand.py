from pathlib import Path
import re

root = Path(r"D:\ai_person\p000_0000_media\hello_novel\novels\time_rift\novel\chapters")

def add(n, extra, tag):
    p = root / f"chapter-{n:03d}.md"
    t = p.read_text(encoding="utf-8")
    if tag in t:
        chars = len(re.sub(r"\s+", "", t.split("本章关键点")[0]))
        print(n, "skip", chars)
        return
    if "\n---\n**本章关键点" in t:
        nt = t.replace("\n---\n**本章关键点", extra + "\n---\n**本章关键点", 1)
    elif "**本章关键点" in t:
        nt = t.replace("**本章关键点", extra + "\n---\n**本章关键点", 1)
    else:
        nt = t + extra
    p.write_text(nt, encoding="utf-8")
    print(n, len(re.sub(r"\s+", "", nt.split("本章关键点")[0])))

