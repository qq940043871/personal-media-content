def ensure_footer(text: str, points: list[str] | None) -> str:
    if points is None:
        return text
    if "本章关键点" in text:
        return text
    block = "\n\n---\n\n**本章关键点：**\n" + "\n".join(f"- {p}" for p in points) + "\n"
    return text.rstrip() + block


def apply_title(ch: str, old: str, new: str, reason: str, points, note_prefix: str = "") -> tuple[bool, str]:
    path = BASE / f"chapter-{ch}.md"
    raw = path.read_text(encoding="utf-8")
    # strip BOM if present
    bom = raw.startswith("\ufeff")
    if bom:
        raw = raw[1:]
    lines = raw.splitlines()
    if not lines:
        return False, "empty"
    first = lines[0]
    expected_old = f"# 第{int(ch)}章 {old}"
    # allow title variants
    if not first.startswith("# 第"):
        return False, f"bad header: {first!r}"
    if old not in first and new not in first:
        return False, f"title mismatch: {first!r} expected contains {old!r}"
    new_first = f"# 第{int(ch)}章 {new}"
    if first.strip() == new_first:
        body = "\n".join(lines[1:])
        body = ensure_footer(body, points)
        new_raw = new_first + body
        if not new_raw.endswith("\n"):
            new_raw += "\n"
        path.write_text(("\ufeff" if bom else "") + new_raw, encoding="utf-8")
        return True, "already titled; footer ensured"
    lines[0] = new_first
    body = "\n".join(lines[1:])
    body = ensure_footer(body, points)
    new_raw = new_first + body
    if not new_raw.endswith("\n"):
        new_raw += "\n"
    path.write_text(("\ufeff" if bom else "") + new_raw, encoding="utf-8")
    return True, f"{old} -> {new}"


