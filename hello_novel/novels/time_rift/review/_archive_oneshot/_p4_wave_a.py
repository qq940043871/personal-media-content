    t, removed = strip_boilerplate(t)
    idx = t.find(key)
    if idx == -1:
        print('WARN ch%s key not found: %s' % (n, key[:20]))
        return
    fm = re.search(r'\n---\n\s*\*\*本章关键点', t)
    if not fm:
        print('WARN ch%s no footer' % n)
        return
    t = t[:idx].rstrip() + '\n\n' + ending.strip() + '\n' + t[fm.start():]
    write_ch(n, t)
    v = verify(n)
    print('ch%s boil_rm=%d cjk=%s dash=%s ok=%s' % (n, removed, v['cjk'], v['dash'], v['ok']))


