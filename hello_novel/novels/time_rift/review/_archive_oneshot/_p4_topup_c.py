def pad(n):
    t = read_ch(n)
    if n in PAD:
        t = ensure_before_footer(t, PAD[n])
    # if still short, weave standard accountability
    while cjk_count(t) < 5000:
        t = ensure_before_footer(t,
            '监察与市政并行抽核：目标、代价、撤回，三句话复述不出来即材料退回。'
            '人类侧公告栏只保留可核对的电、电梯、窗口、纸张、班表。'
            '失败账三行格式不得删减；对地三样本平稳也是账。')
        if cjk_count(t) >= 5000:
            break
        # one more unique line to avoid infinite same-block
        t = ensure_before_footer(t,
            '联盟内部可争论更大的问题；人间侧必须保留说不、可撤回、按账办的权利。'
            '看见不等于可以拿走，讨论不等于授权，授权不等于免检。')
        break
    # dash cap
    while t.count('——') > 8:
        i = t.find('——')
        if i < 0:
            break
        # protect footer
        fm = t.find('**本章关键点')
        if fm != -1 and i > fm:
            break
        t = t[:i] + '，' + t[i+2:]
    write_ch(n, t)
    v = verify(n)
    print('ch%s cjk=%s dash=%s ok=%s' % (n, v['cjk'], v['dash'], v['ok']))
    return v

