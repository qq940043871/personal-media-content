def count_cjk(text):
    return len(re.findall(r'[\u4e00-\u9fff]', text))

def apply_one(n, spec):
    p = CH / f'chapter-{n:03d}.md'
    raw = p.read_text(encoding='utf-8')
    if raw.startswith('\ufeff'):
        raw = raw[1:]
    before = count_cjk(raw)
    exp = spec['text']
    needle = spec.get('insert_before')
    if needle and needle in raw:
        raw2 = raw.replace(needle, exp.strip() + '\n\n' + needle, 1)
        how = 'ok'
    else:
        for alt in ['公告栏玻璃反着光', '小巷深处的木牌', '楼梯转角的配电箱', '林晓实验室',
                    '墙上的观察窗标记旁', '她走在走廊里', '她在学习用自己的声音说话',
                    '楼梯转角的配电箱门虚掩着']:
            if alt in raw:
                raw2 = raw.replace(alt, exp.strip() + '\n\n' + alt, 1)
                how = 'alt'
                break
        else:
            if '\n---\n**本章关键点' in raw:
                raw2 = raw.replace('\n---\n**本章关键点', '\n' + exp + '\n---\n**本章关键点', 1)
            else:
                raw2 = raw.rstrip() + '\n' + exp
            how = 'footer'
    p.write_text(raw2, encoding='utf-8')
    after = count_cjk(raw2)
    print(f'ch{n}: {before}→{after} {"OK" if after>=5000 else "SHORT"} ({how})')

