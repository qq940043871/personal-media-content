def extract_footer_span(text: str):
    m = re.search(r"(\n---\s*\n\*\*本章关键点[：:]?\*\*\s*\n)([\s\S]+)$", text)
    if not m:
        # try without leading ---
        m2 = re.search(r"(\*\*本章关键点[：:]?\*\*\s*\n)([\s\S]+)$", text)
        if not m2:
            return None
        return m2.start(1), m2.end()
    return m.start(1), m.end()


def apply_one(n: int, bullets: list) -> dict:
    p = CHDIR / f"chapter-{n:03d}.md"
    if not p.exists():
        return {"n": n, "ok": False, "err": "missing"}
    text = p.read_text(encoding="utf-8")
    span = extract_footer_span(text)
    if not span:
        return {"n": n, "ok": False, "err": "no_footer_span"}
    s, e = span
    header = text[s:s + len(text[s:e])]
    # keep the header part (**本章关键点：**\n and optional ---\n before it)
    m = re.search(r"((?:\n---\s*\n)?\*\*本章关键点[：:]?\*\*\s*\n)", text[s:e])
    if not m:
        return {"n": n, "ok": False, "err": "header_parse"}
    keep_head = m.group(1)
    new_footer = keep_head + "\n".join(f"- {b}" for b in bullets) + "\n"
    # preserve anything after footer? Usually footer is EOF. Keep trailing whitespace minimal.
    new_text = text[:s] + new_footer
    # if old text had trailing content after footer (rare), drop only footer body
    p.write_text(new_text, encoding="utf-8")
    return {"n": n, "ok": True, "bullets": len(bullets), "title_line": text.splitlines()[0] if text else ""}


