def apply_topup(n: int, text: str):
    p = CH / f"chapter-{n:03d}.md"
    raw = p.read_text(encoding="utf-8")
    if raw.startswith("\ufeff"):
        raw = raw[1:]
    before = body_cjk(raw)
    if before >= 5000:
        print(f"ch{n}: already OK cjk={before}")
        return before
    marker = f"P6E-NOTE-{n}"
    block = text.strip()
    # avoid duplicate if same unique phrase already present
    key = block[:24]
    if key in raw:
        print(f"ch{n}: marker present, cjk={before}, force footer insert anyway")
    out, how = insert_before_footer(raw, block + "\n")
    p.write_text(out, encoding="utf-8")
    after = body_cjk(out)
    d = body_dash(out)
    flag = "OK" if after >= 5000 else "SHORT"
    print(f"ch{n}: {before}→{after} {flag} dash={d} ({how})")
    return after


