def compress_body_dash(path: Path, keep_max_units: int = 4) -> tuple[int, int]:
    """Compress explanatory em-dashes in body only. Returns (before, after) single counts."""
    raw = path.read_text(encoding="utf-8")
    if raw.startswith("\ufeff"):
        raw = raw[1:]
    body, footer = split_body_footer(raw)
    before = len(re.findall(r"\u2014", body))

    lines = body.splitlines()
    title_line = ""
    body_only = []
    for i, line in enumerate(lines):
        if i == 0 and line.startswith("# "):
            title_line = line
        else:
            body_only.append(line)
    text = "\n".join(body_only)

    dashes = [(m.start(), m.group()) for m in re.finditer(r"\u2014\u2014|\u2014", text)]
    if len(dashes) <= keep_max_units:
        return before, before

    def is_dramatic(before_s, after_s):
        b = before_s[-24:] if before_s else ""
        if re.search(r"[\"「][^\」\"]{0,12}$", b):
            return True
        if re.search(r"(是|但|因为|不|我|你|他|她|它|却|而)$", b) and after_s:
            return True
        # Morse / death-bed patterns
        if "太" in b[-3:] or "阳" in b[-3:]:
            return True
        return False

    replacements = []
    kept = 0
    for pos, g in dashes:
        end = pos + len(g)
        before_s = text[:pos]
        after_s = text[end:]
        # always keep Morse-like pattern 太——阳——真——美
        ctx = before_s[-2:] + after_s[:2]
        if re.search(r"太|阳|真|美", ctx) and g == "\u2014\u2014":
            # only keep if it's part of the final Morse line
            window = before_s[-4:] + g + after_s[:6]
            if "阳" in window or "美" in window or "真" in window:
                kept += 1
                continue
        if is_dramatic(before_s, after_s) and kept < keep_max_units:
            kept += 1
            continue
        b = before_s[-20:] if before_s else ""
        a = after_s[:20] if after_s else ""
        if re.search(r"[，。；：？！]$", b) or (a[:1] in " ，。"):
            new = ""
        elif re.search(r"是$|为$|叫$|称$|做$|像$|非$", b):
            new = "，"
        else:
            new = "，"
        if new:
            if b and b[-1] in "，。；：？！、":
                new = ""
            if a and a[:1] in "，。；：？！、":
                new = ""
        replacements.append((pos, end, new))

    for start, end, new in sorted(replacements, key=lambda x: -x[0]):
        text = text[:start] + new + text[end:]

    new_body_lines = []
    if title_line:
        new_body_lines.append(title_line)
    new_body_lines.extend(text.splitlines())
    new_body = "\n".join(new_body_lines).rstrip() + "\n"

    out = new_body
    if footer:
        if not footer.startswith("---"):
            footer = "---\n" + footer
        if not out.endswith("\n"):
            out += "\n"
        out += footer
