def strip_bom(raw):
    return raw[1:] if raw.startswith("\ufeff") else raw


def split_body_footer(raw):
    raw = strip_bom(raw)
    lines = raw.splitlines()
    footer_idx = None
    for i, line in enumerate(lines):
        if re.match(r"^---\s*$", line):
            window = "\n".join(lines[i + 1 : i + 8])
            if FOOTER_MARK in window or "本章围绕" in window:
                footer_idx = i
    if footer_idx is None:
        m = re.search(r"\n---\s*\n\*\*本章关键点", raw)
        if m:
            return raw[: m.start()] + "\n", raw[m.start() :]
        return raw.rstrip() + "\n", ""
    body = "\n".join(lines[:footer_idx]).rstrip() + "\n"
    footer = "\n".join(lines[footer_idx:])
    return body, footer


def body_cjk(text):
    body, _ = split_body_footer(text)
    lines = body.splitlines()
    body_lines = [l for i, l in enumerate(lines) if not (i == 0 and l.startswith("# "))]
    return len(re.findall(r"[\u4e00-\u9fff]", "\n".join(body_lines)))


def body_dash(text):
    body, _ = split_body_footer(text)
    lines = body.splitlines()
    body_lines = [l for i, l in enumerate(lines) if not (i == 0 and l.startswith("# "))]
    return len(re.findall(r"\u2014", "\n".join(body_lines)))


def insert_before_footer(raw, block):
    body, footer = split_body_footer(raw)
    marker = block.strip()[:40]
    if marker and marker in body:
        return raw, "skip-marker"
    out = body.rstrip() + "\n\n" + block.strip() + "\n\n"
    if footer:
        if not footer.startswith("---"):
            footer = "---\n" + footer
        if not out.endswith("\n"):
            out += "\n"
        out += footer
    if not out.endswith("\n"):
        out += "\n"
    return out, "footer"


