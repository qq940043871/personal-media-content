def apply_expand(n: int, path: Path, block: str) -> tuple[int, int]:
    text = path.read_text(encoding="utf-8-sig")
    _, _, _, cjk, _ = split_chapter(text)
    m = FOOTER_RE.search(text)
    if not m:
        return cjk, cjk
    fingerprint = None
    for line in block.splitlines():
        s = line.strip()
        if s.startswith("## ") and len(s) >= 6:
            fingerprint = s
            break
    if fingerprint and fingerprint in text:
        return cjk, cjk
    if f"P4扩写2·{n:03d}" in text:
        return cjk, cjk
    payload = f"\n{block.rstrip()}\n"
    new_text = text[: m.start()] + payload + text[m.start() :]
    path.write_text(new_text, encoding="utf-8")
    _, _, _, cjk2, _ = split_chapter(path.read_text(encoding="utf-8-sig"))
    return cjk, cjk2


