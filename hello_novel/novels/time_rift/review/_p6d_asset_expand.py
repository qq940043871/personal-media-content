CJK = re.compile(r"[\u4e00-\u9fff]")


def body_of(text: str) -> str:
    if text.startswith("\ufeff"):
        text = text[1:]
    lines = text.splitlines()
    body_lines = []
    skip_title = True
    for i, line in enumerate(lines):
        if skip_title and line.startswith("# "):
            skip_title = False
            continue
        if line.strip() == "---" and any("本章关键点" in l for l in lines[i:]):
            break
        if line.startswith(">"):
            continue
        body_lines.append(line)
    return "\n".join(body_lines)


def dash_units(body: str) -> int:
    return len(re.findall(r"——", body))


def stats(n: int) -> tuple[int, int]:
    text = (BASE / f"chapter-{n:03d}.md").read_text(encoding="utf-8")
    body = body_of(text)
    return len(CJK.findall(body)), dash_units(body)


def replace_once(path: Path, old: str, new: str) -> None:
    text = path.read_text(encoding="utf-8")
    if old not in text:
        raise SystemExit(f"ANCHOR MISS in {path.name}:\n{old[:80]!r}")
    if text.count(old) != 1:
        raise SystemExit(f"ANCHOR MULTI in {path.name}: count={text.count(old)}")
    path.write_text(text.replace(old, new, 1), encoding="utf-8")


