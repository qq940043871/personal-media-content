CJK = re.compile(r"[\u4e00-\u9fff]")

def body_cjk(text):
    lines = []
    for ln in text.splitlines():
        if re.match(r"^#\s*第\d+章", ln):
            continue
        if "本章关键点" in ln:
            break
        lines.append(ln)
    return len(CJK.findall("\n".join(lines)))

def split(text):
    t = text.lstrip("\ufeff")
    m = re.match(r"^(#\s*第\d+章[^\n]*)\n([\s\S]*)$", t)
    title, rest = m.group(1), m.group(2)
    idx = rest.find("**本章关键点")
    if idx >= 0:
        body = re.sub(r"\n---\s*$", "", rest[:idx].rstrip()) + "\n"
        footer = rest[idx:]
    else:
        body, footer = rest.rstrip() + "\n", ""
    return title, body, footer

def reduce_dashes(body, cap=6):
    while len(re.findall(r"——", body)) > cap:
        idx = body.rfind("——")
        if idx < 0:
            break
        body = body[:idx] + "，" + body[idx+2:]
    return body

def make_footer(bullets):
    return "\n---\n\n**本章关键点：**\n" + "\n".join(f"- {b}" for b in bullets) + "\n"

def apply(ch, insert, footer_bullets, force_footer=False):
    p = CH / f"chapter-{ch:03d}.md"
    raw = p.read_text(encoding="utf-8")
    title, body, footer = split(raw)
    before = body_cjk(raw)
    if before >= 5000 and not force_footer:
        print(f"skip ok ch{ch} {before}")
        return
    body = re.sub(r"\n补记：[^\n]*", "", body)
    body = body.rstrip() + "\n" + insert
    body = reduce_dashes(body, 6)
    if force_footer or "格式：页脚已补" in footer or "本章围绕" in footer:
        footer = make_footer(footer_bullets)
    new = title + "\n" + body.rstrip() + "\n" + footer
    if not new.endswith("\n"):
        new += "\n"
    p.write_text(new, encoding="utf-8")
    after = body_cjk(new)
    dash = len(re.findall(r"——", re.sub(r"^\s*---\s*$", "", new[:new.find("**本章关键点")], flags=re.M)))
    ok = after >= 5000 and dash <= 8
    print(f"ch{ch} {before}->{after} dash={dash} {'OK' if ok else 'NEED'}")

