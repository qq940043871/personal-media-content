def apply_expand(n, path, block):
    text = path.read_text(encoding="utf-8-sig")
    cjk, _ = split_chapter(text)
    m = FOOTER_RE.search(text)
    if not m:
        return cjk, cjk
    fingerprint = None
    for line in block.splitlines():
        s = line.strip()
        if s.startswith("## ") and len(s) >= 4:
            fingerprint = s
            break
    if fingerprint and fingerprint in text:
        return cjk, cjk
    if f"P4扩写4·{n:03d}" in text:
        return cjk, cjk
    new_text = text[: m.start()] + block.rstrip() + "\n" + text[m.start() :]
    path.write_text(new_text, encoding="utf-8")
    cjk2, _ = split_chapter(path.read_text(encoding="utf-8-sig"))
    return cjk, cjk2


