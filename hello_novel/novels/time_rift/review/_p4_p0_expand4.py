FOOTER_RE = re.compile(r"\n---\s*\n\*\*本章关键点[：:]\*\*", re.M)
TITLE_RE = re.compile(r"^#[^\n]*\n")
CJK_RE = re.compile(r"[\u4e00-\u9fff]")


def split_chapter(text: str):
    m = FOOTER_RE.search(text)
    head_body = text[: m.start()] if m else text
    title_m = TITLE_RE.match(head_body)
    title = title_m.group(0) if title_m else ""
    body = head_body[len(title) :]
    measure = re.sub(r"^(?:---\s*\n)?(?:>.*\n)+", "", body)
    measure = re.sub(r"^---\s*\n", "", measure)
    return len(CJK_RE.findall(measure)), body.count("——")


