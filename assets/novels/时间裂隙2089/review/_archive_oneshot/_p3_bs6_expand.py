def cjk_body(text):
    body = re.sub(r'^# 第\d+章[^\n]*\n?', '', text)
    body = re.split(r'\n---\n\s*\*\*本章关键点', body)[0]
    return len(re.findall(r'[\u4e00-\u9fff]', body))

def ensure(path, add_body, footer_bullets):
    with open(path, 'r', encoding='utf-8') as f:
        text = f.read()
    has_fp = '**本章关键点' in text
    if has_fp:
        text2 = re.sub(r'(\n---\n\s*\*\*本章关键点)', '\n' + add_body + r'\1', text, count=1)
        text2 = re.sub(
            r'\n---\n\s*\*\*本章关键点：\*\*[\s\S]*$',
            '\n---\n**本章关键点：**\n' + '\n'.join('- ' + b for b in footer_bullets) + '\n',
            text2,
        )
    else:
        text2 = text.rstrip() + '\n\n' + add_body + '\n\n---\n**本章关键点：**\n' + '\n'.join('- ' + b for b in footer_bullets) + '\n'
    with open(path, 'w', encoding='utf-8') as f:
        f.write(text2)
    return cjk_body(text2)

