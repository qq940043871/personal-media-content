def ensure_footer(path: Path, footer_block: str) -> None:
    t = path.read_text(encoding="utf-8-sig")
    if FOOTER_RE.search(t):
        # replace empty/stub footer body if needed
        m = FOOTER_RE.search(t)
        after = t[m.start() :]
        # if footer has fewer than 2 bullet lines, replace whole footer
        bullets = len(re.findall(r"^- ", after, re.M))
        if bullets >= 2:
            return
        t = t[: m.start()] + footer_block
        path.write_text(t, encoding="utf-8")
        return
    t = t.rstrip() + "\n\n" + footer_block
    path.write_text(t, encoding="utf-8")


def apply_block(n: int, block: str) -> tuple[int, int]:
    p = ROOT / f"chapter-{n:03d}.md"
    t = p.read_text(encoding="utf-8-sig")
    before = sc(t)
    # marker unique heading
    fp = None
    for line in block.splitlines():
        s = line.strip()
        if s.startswith("## ") and len(s) >= 5:
            fp = s
            break
    if fp and fp in t:
        return before, before
    m = FOOTER_RE.search(t)
    if not m:
        # append block then footer
        if n in FOOTERS:
            t = t.rstrip() + "\n" + block + "\n" + FOOTERS[n]
        else:
            t = t.rstrip() + "\n" + block + "\n\n---\n**本章关键点：**\n"
        p.write_text(t, encoding="utf-8")
        return before, sc(p.read_text(encoding="utf-8-sig"))
    t = t[: m.start()] + block + t[m.start() :]
    p.write_text(t, encoding="utf-8")
    return before, sc(p.read_text(encoding="utf-8-sig"))


