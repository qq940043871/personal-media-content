def ensure_footer(path: Path, footer_block: str) -> None:
    t = path.read_text(encoding="utf-8-sig")
    m = FOOTER_RE.search(t)
    if m:
        after = t[m.start() :]
        bullets = len(re.findall(r"^- ", after, re.M))
        if bullets >= 2:
            return
        path.write_text(t[: m.start()] + footer_block, encoding="utf-8")
        return
    path.write_text(t.rstrip() + "\n\n" + footer_block, encoding="utf-8")


def apply_block(n: int, block: str) -> tuple[int, int]:
    p = ROOT / f"chapter-{n:03d}.md"
    t = p.read_text(encoding="utf-8-sig")
    before = sc(t)
    fp = None
    for line in block.splitlines():
        s = line.strip()
        if s.startswith("## ") and len(s) >= 5:
            fp = s
            break
    if fp and fp in t:
        return before, before
    m = FOOTER_RE.search(t)
    if not m:
        foot = FOOTERS.get(n, "\n---\n**本章关键点：**\n")
        t = t.rstrip() + "\n" + block + "\n" + foot
        p.write_text(t, encoding="utf-8")
        return before, sc(p.read_text(encoding="utf-8-sig"))
    t = t[: m.start()] + block + t[m.start() :]
    p.write_text(t, encoding="utf-8")
    return before, sc(p.read_text(encoding="utf-8-sig"))


def main() -> None:
    for n, foot in FOOTERS.items():
        ensure_footer(ROOT / f"chapter-{n:03d}.md", foot)
