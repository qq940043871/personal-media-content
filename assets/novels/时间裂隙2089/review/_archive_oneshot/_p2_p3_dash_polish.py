def count_dashes(text: str) -> int:
    return len(re.findall("——", text))


def main() -> None:
    results = []
    for ch, pairs in edits.items():
        path = CHAPTERS / f"chapter-{ch:03d}.md"
        text = path.read_text(encoding="utf-8")
        before = count_dashes(text)
        applied = 0
        missing = []
        for old, new in pairs:
            if old not in text:
                missing.append(old[:50])
                continue
            cnt = text.count(old)
            text = text.replace(old, new)
            applied += cnt
        after = count_dashes(text)
        path.write_text(text, encoding="utf-8")
        results.append((ch, before, after, applied, missing))

    print(f"{'ch':>4} {'before':>6} {'after':>5} {'repl':>4} missing")
    for ch, b, a, ap, miss in results:
        m = f" MISS:{len(miss)}" if miss else ""
        print(f"{ch:>4} {b:>6} {a:>5} {ap:>4}{m}")
        for x in miss:
            print(f"       ! {x}")


if __name__ == "__main__":
    main()
