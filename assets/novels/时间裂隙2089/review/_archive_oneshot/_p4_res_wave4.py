def process(n):
    t = read_ch(n)
    if t.startswith('\ufeff'):
        t = t.lstrip('\ufeff')
    t2, removed = strip_boilerplate(t)
    t3 = insert_narrative(t2, FULL[n])
    t3 = replace_footer(t3, FOOTERS[n])
    if t3.startswith('\ufeff'):
        t3 = t3.lstrip('\ufeff')
    t3 = re.sub(r'\n{4,}', '\n\n\n', t3)
    cjk = cjk_count(t3)
    dash = dash_count(t3)
    foot = has_footer(t3)
    ok = cjk >= 5000 and dash <= 8 and foot
    print(f'n={n} removed={removed} cjk={cjk} dash={dash} foot={foot} ok={ok}')
    if not ok:
        print(f'  FAIL need_cjk={max(0,5000-cjk)} need_dash={max(0,dash-8)}')
        return False
    write_ch(n, t3)
    return True


