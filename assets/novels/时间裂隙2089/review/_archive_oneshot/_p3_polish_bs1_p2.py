def main():
    total = 0
    for f in sorted(BASE.glob("chapter-*.md")):
        t = f.read_text(encoding="utf-8")
        orig = t
        n = 0
        for old, new in FIXES:
            if old in t:
                c = t.count(old)
                t = t.replace(old, new)
                n += c
                LOG[f.name].append(f"x{c}: {old[:40]} → {new[:40]}")
        if t != orig:
            f.write_text(t, encoding="utf-8")
            print(f"{f.name}: {n}")
            total += n
    print(f"TOTAL pass2: {total}")

    # final residual checks
    TOKEN = "\\1"
    residual = 0
    awkward = 0
    for f in sorted(BASE.glob("chapter-*.md")):
        t = f.read_text(encoding="utf-8")
        residual += t.count(TOKEN)
        # only count awkward that look like OUR artifacts (……。 mid-narrative that is incomplete)
        for m in re.finditer(r"是……。|而是……。|被……。|像……。|只……。", t):
            s = max(0, m.start() - 20)
            e = min(len(t), m.end() + 40)
            print(f"STILL AWKWARD {f.name}: ...{t[s:e]}...")
            awkward += 1
    print(f"RESIDUAL \\1: {residual}")
    print(f"STILL AWKWARD incomplete: {awkward}")

    log_path = Path(r"D:/ai_person/p000_0000_media/hello_novel/novels/time_rift/review/_p3_bs1_pass2_log.txt")
    lines = [f"TOTAL pass2: {total}", ""]
    for ch, notes in sorted(LOG.items()):
        lines.append(f"## {ch}")
        lines.extend(notes)
        lines.append("")
    log_path.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
