def apply_one(n: int, bullets: list) -> dict:
    p = CHDIR / f"chapter-{n:03d}.md"
    if not p.exists():
        return {"n": n, "ok": False, "err": "missing"}
    text = p.read_text(encoding="utf-8")
    m = re.search(r"((?:\n---\s*\n)?\*\*本章关键点[：:]?\*\*\s*\n)([\s\S]+)$", text)
    if not m:
        return {"n": n, "ok": False, "err": "no_footer"}
    keep_head = m.group(1)
    new_text = text[: m.start()] + keep_head + "\n".join(f"- {b}" for b in bullets) + "\n"
    p.write_text(new_text, encoding="utf-8")
    return {"n": n, "ok": True}


def main():
    results = []
    for n, bullets in sorted(FOOTERS.items()):
        assert 3 <= len(bullets) <= 5, (n, len(bullets))
        joined = "\n".join(bullets)
        stripped = joined.replace("新上海", "").replace("上海", "")
        bad = []
        if "陈远桥" in joined:
            bad.append("陈远桥")
        if "梦" in joined:
            bad.append("梦")
        if "海" in stripped:
            bad.append("海")
        if f"第{n}章" in joined or "本批" in joined or "C 类" in joined:
            bad.append("meta")
        if "相关公开口径暂不升格" in joined or "机械臂读数或共振代价写入失败账" in joined:
            bad.append("boiler")
        if bad:
            results.append({"n": n, "ok": False, "err": bad})
            continue
        results.append(apply_one(n, bullets))
    ok = sum(1 for r in results if r.get("ok"))
    fail = [r for r in results if not r.get("ok")]
    print(f"applied={ok} failed={len(fail)}")
    for r in fail:
        print(r)
    for n in [62, 67, 72, 95, 113, 119]:
        t = (CHDIR / f"chapter-{n:03d}.md").read_text(encoding="utf-8")
        m = re.search(r"\*\*本章关键点[：:]?\*\*\s*\n([\s\S]+)$", t)
        print(f"\n--- {n} ---")
        print(m.group(0)[:280] if m else "NONE")


if __name__ == "__main__":
    main()
