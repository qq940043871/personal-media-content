def ensure_footer(path: Path, num: int) -> str:
    raw = path.read_bytes()
    text = raw.decode("utf-8")
    if "**本章关键点：**" in text:
        return "skip"
    items = FOOTERS.get(num)
    if not items:
        return "no-footer-map"
    # strip trailing whitespace but keep final newline
    body = text.rstrip() + "\n"
    # strip BOM if present at start for cleanliness later; don't rewrite whole file encoding issues
    footer = "\n---\n**本章关键点：**\n" + "\n".join(f"- {x}" for x in items) + "\n"
    path.write_text(body + footer, encoding="utf-8")
    return "ok"


def main():
    results = {"ok": 0, "skip": 0, "no-footer-map": []}
    for p in sorted(BASE.glob("chapter-*.md")):
        m = re.search(r"chapter-(\d+)", p.name)
        if not m:
            continue
        num = int(m.group(1))
        # only touch known missing set ranges
        if not (1 <= num <= 60 or 301 <= num <= 338):
            # still check all for residual
            text = p.read_text(encoding="utf-8")
            if "**本章关键点：**" not in text:
                r = ensure_footer(p, num)
                if r == "ok":
                    results["ok"] += 1
                elif r == "skip":
                    results["skip"] += 1
                else:
                    results["no-footer-map"].append(p.name)
            continue
        r = ensure_footer(p, num)
        if r == "ok":
            results["ok"] += 1
        elif r == "skip":
            results["skip"] += 1
        else:
            results["no-footer-map"].append(p.name)
    print("ok", results["ok"], "skip", results["skip"], "unmapped", results["no-footer-map"])


if __name__ == "__main__":
    main()
