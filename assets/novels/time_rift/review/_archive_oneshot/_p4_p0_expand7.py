def apply(n, path, block):
    text = path.read_text(encoding="utf-8-sig")
    cjk, _ = split_chapter(text)
    m = FOOTER_RE.search(text)
    if not m:
        return cjk, cjk
    fp = None
    for line in block.splitlines():
        s = line.strip()
        if s.startswith("## ") and len(s) >= 4:
            fp = s
            break
    if fp and fp in text:
        return cjk, cjk
    path.write_text(text[: m.start()] + block + text[m.start() :], encoding="utf-8")
    return cjk, split_chapter(path.read_text(encoding="utf-8-sig"))[0]


def main():
    for n, block in B.items():
        p = ROOT / f"chapter-{n:03d}.md"
        if not p.exists():
            continue
        a, b = apply(n, p, block)
        print(f"{n:03d} {a}->{b}")
    print("=== FINAL ===")
    for n in range(61, 121):
        p = ROOT / f"chapter-{n:03d}.md"
        if not p.exists():
            continue
        t = p.read_text(encoding="utf-8-sig")
        cjk, dash = split_chapter(t)
        if cjk < 4500 or dash > 8 or n in (61, 83, 84, 89, 96, 105, 112, 120):
            mark = ""
            if cjk < 4500:
                mark = " <4500"
            print(f"{n:03d} cjk={cjk} dash={dash}{mark}")


if __name__ == "__main__":
    main()
