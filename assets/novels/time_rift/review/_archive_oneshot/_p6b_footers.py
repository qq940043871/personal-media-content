def set_footer(n, bullets):
    p = base / ("chapter-%d.md" % n)
    if not p.exists():
        print("missing", n)
        return
    raw = strip_bom(p.read_text(encoding="utf-8"))
    lines = raw.splitlines()
    fi = _footer_index(lines)
    body = "\n".join(lines[:fi]).rstrip() if fi is not None else raw.rstrip()
    footer = ["---", "**本章关键点：**"] + bullets
    out = body + "\n\n" + "\n".join(footer) + "\n"
    p.write_text(out, encoding="utf-8")
    print("footer ch%d cjk=%d dash=%d" % (n, body_cjk(out), dash_count(out)))


def main():
    for n, bullets in FOOTERS.items():
        set_footer(n, bullets)

if __name__ == "__main__":
    main()
