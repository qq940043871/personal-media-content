CJK = re.compile(r"[\u4e00-\u9fff]")

def body_cjk(text):
    lines = []
    for ln in text.splitlines():
        if re.match(r"^#\s*第\d+章", ln):
            continue
        if "本章关键点" in ln:
            break
        lines.append(ln)
    return len(CJK.findall("\n".join(lines)))

def split(text):
    t = text.lstrip("\ufeff")
    m = re.match(r"^(#\s*第\d+章[^\n]*)\n([\s\S]*)$", t)
    if not m:
        return None, t, ""
    title, rest = m.group(1), m.group(2)
    idx = rest.find("**本章关键点")
    if idx >= 0:
        body = rest[:idx]
        body = re.sub(r"\n---\s*$", "", body.rstrip()) + "\n"
        footer = rest[idx:]
    else:
        body, footer = rest.rstrip() + "\n", ""
    return title, body, footer

def reduce_dashes(body, cap=6):
    body = re.sub(r"——不是([^—\n]{1,24})，而是", r"不是\1，而是", body)
    body = re.sub(r"不是([^—\n]{1,24})——而是", r"不是\1，而是", body)
    body = re.sub(r"关键不在([^—\n]{1,30})——", r"关键不在\1，", body)
    body = re.sub(r"与其说([^—\n]{1,20})——不如", r"与其说\1，不如", body)
    body = re.sub(r"与其说是不是([^—\n]{1,20})——", r"与其说\1，", body)
    while len(re.findall(r"——", body)) > cap:
        idx = body.rfind("——")
        if idx < 0:
            break
        body = body[:idx] + "，" + body[idx+2:]
    return body

def make_footer(name, bullets):
    return "\n---\n\n**本章关键点：**\n" + "\n".join(f"- {b}" for b in bullets) + "\n"

