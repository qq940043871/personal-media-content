FOOTER_SNIP = (
    "\n- 城市锚点补记：{city}\n"
    "- 人话锚补记：店长「下来个人签收」；周晚晴「空的不算正常，算没人看过」；老何「不写已恢复」\n"
)


def insert_dense(ch: int, text: str) -> str:
    block = DENSE[ch]
    if "李明把机械臂横在两人之间" in text:
        return text
    # insert before last --- **本章关键点, or at ## 三 / ## 四 if present
    m = re.search(r"\n## 三\n", text)
    if m:
        return text[: m.start()] + block + text[m.start() :]
    m = re.search(r"\n## 四\n", text)
    if m:
        return text[: m.start()] + block + text[m.start() :]
    m = re.search(r"\n---\s*\n\*\*本章关键点", text)
    if m:
        return text[: m.start()] + block + text[m.start() :]
    return text.rstrip() + "\n" + block


def insert_city(ch: int, text: str) -> str:
    city = CITY_ONLY[ch]
    if "城市锚点补记" in text:
        return text
    m = re.search(r"\n---\s*\n\*\*本章关键点[\s\S]*$", text)
    if not m:
        return text
    body = text[: m.start()]
    footer = text[m.start() :]
    # city paragraph before footer
    para = (
        "\n---\n\n"
        "同一时刻，地面侧记录。\n\n"
        + city
        + "\n"
    )
    footer_add = FOOTER_SNIP.format(city=city[:60] + "…")
    if footer.rstrip().endswith("```"):
        pass
    # append city anchor bullets if not present
    if "- 城市锚点" in footer:
        footer = footer.rstrip() + "\n" + footer_add
    else:
        footer = footer.rstrip() + "\n" + footer_add
    return body.rstrip() + "\n" + para + footer


def main() -> None:
    for ch, _ in DENSE.items():
        p = CH_DIR / f"chapter-{ch:03d}.md"
        if not p.exists():
            print(f"MISSING {ch}")
            continue
        text = p.read_text(encoding="utf-8")
        new = insert_dense(ch, text)
        if new != text:
            p.write_text(new, encoding="utf-8")
            print(f"DENSE OK {ch}")
        else:
            print(f"DENSE SKIP {ch}")

    for ch, _ in CITY_ONLY.items():
        p = CH_DIR / f"chapter-{ch:03d}.md"
        if not p.exists():
            print(f"MISSING city {ch}")
            continue
        text = p.read_text(encoding="utf-8")
        new = insert_city(ch, text)
        if new != text:
            p.write_text(new, encoding="utf-8")
            print(f"CITY OK {ch}")
        else:
            print(f"CITY SKIP {ch}")


if __name__ == "__main__":
    main()
