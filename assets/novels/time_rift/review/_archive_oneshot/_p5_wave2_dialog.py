def main() -> None:
    for ch, rules in INTERRUPT.items():
        p = CH_DIR / f"chapter-{ch:03d}.md"
        if not p.exists():
            print(f"MISSING {ch}")
            continue
        text = p.read_text(encoding="utf-8")
        changed = False
        for pat, insert in rules:
            if "先别往下讲" in insert[:20] or "等一下" in insert[:20] or "结构变化四个字" in insert[:20] or "停。」李明" in insert[:20] or "传播之前" in insert[:20] or "希望不能" in insert[:20] or "连接税是谁" in insert[:20]:
                # uniqueness guard by first line of insert
                key = insert.strip().splitlines()[0]
                if key in text:
                    print(f"SKIP insert (already) {ch}: {key[:20]}")
                    continue
            new_text, n = re.subn(pat, insert, text, count=1)
            if n:
                text = new_text
                changed = True
            else:
                print(f"NO ANCHOR {ch}: {pat}")
        if changed:
            p.write_text(text, encoding="utf-8")
            print(f"OK {ch}")
        else:
            print(f"NOCHANGE {ch}")


if __name__ == "__main__":
    main()
